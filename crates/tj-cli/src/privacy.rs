//! Personal data on the command line (docs/privacy.md): `tj check --privacy` prints the data
//! map, and `tj privacy export|erase <person>` asks a running server for a person's data or
//! erases it.

use tj_core::modules;
use tj_core::vm::program::{Program, SPECIAL_CATEGORIES};

/// The data map: every personal-data field with its category, purposes and readers.
pub fn report(program: &Program) -> String {
    let mut out = String::new();
    for o in program.objects.iter().filter(|o| !o.pii.is_empty()) {
        let read = o.read.as_ref().map_or("server code only".to_string(), |r| r.join(", "));
        let whose = if o.belongs_to_a_person() { "id: the person's id" } else { "shared" };
        out.push_str(&format!("{}  ({whose}; read: {read})\n", o.name));
        for p in &o.pii {
            let special = if SPECIAL_CATEGORIES.contains(&&*p.category) { "  special category" } else { "" };
            let by = p.by.as_ref().map_or_else(String::new, |(who, _)| format!("  each entry is the person its `{who}` names"));
            let seen = o.guards.iter().find(|g| g.field == p.field).map_or_else(String::new, |g| g.rule.join(", "));
            out.push_str(&format!("  {}  {}{special}  for {}{by}  seen by: {seen}\n", p.field, p.category, p.purposes.join(", ")));
        }
        out.push_str(&format!("  kept: {}\n", kept(o)));
    }
    for o in &program.objects {
        for g in o.guards.iter().filter(|g| g.names_a_person()) {
            out.push_str(&format!("{}.{}  names a person (seen by: {}): exported and erased with them\n", o.name, g.field, g.rule.join(", ")));
        }
    }
    if out.is_empty() {
        return "no personal data: mark fields with @pii(category, purpose)\n".into();
    }
    out.push_str("Each field is seen by the readers named (\"owner\": the person whose id is the object's; \"self\": the person the field names); everyone else sees ••• (a field naming a person: its default), and every tool sees •••.\n");
    out.push_str("Every compile checks where these values flow (docs/privacy.md); each reveal(value, purpose) lets one path through.\n");
    out
}

/// How long an object is kept, with its legal hold.
fn kept(o: &tj_core::vm::program::ObjectDef) -> String {
    let at = o.pii.iter().find_map(|p| p.by.as_ref().and_then(|(_, at)| at.clone()));
    let kept = match (o.retain, at) {
        (Some(r), Some(at)) if !o.belongs_to_a_person() => format!("each entry erased {} after its `{at}`", span(r.ms)),
        (Some(r), _) => format!("erased {} after it was {}", span(r.ms), if r.from_created { "created" } else { "last changed" }),
        (None, _) if !o.belongs_to_a_person() => "each entry until its person is erased".to_string(),
        (None, _) => "until the person is erased".to_string(),
    };
    let hold = o.hold.map_or_else(String::new, |h| format!("; at least {} after the last change, even when erased (legal hold)", span(h)));
    kept + &hold
}

/// A duration in the largest whole unit that fits: days, hours or minutes.
fn span(ms: f64) -> String {
    let (n, unit) = [(86_400_000.0, "day"), (3_600_000.0, "hour"), (60_000.0, "minute")].into_iter().map(|(u, name)| (ms / u, name)).find(|(n, _)| *n >= 1.0).unwrap_or((ms / 60_000.0, "minute"));
    let n = (n * 10.0).round() / 10.0;
    format!("{n} {unit}{}", if n == 1.0 { "" } else { "s" })
}

/// The record of processing (GDPR article 30) the code can state, as Markdown: what
/// personal data is held, about whom and why, where it is let out, how long it is kept, and
/// the measures the runtime provides. What only people know is left blank to fill in.
pub fn record(src: &str, program: &Program) -> String {
    let mut out = String::from("# Record of processing activities (GDPR article 30; Saudi PDPL)\n\nGenerated by `tj check --privacy --record` from the app's code. Fill in the blanks.\n\n- **Controller, contact and data protection officer:** ____\n- **Whose data (customers, staff, ...):** ____\n- **Lawful basis for each purpose:** ____\n- **Recipients and processors (hosting, and the services reached where data is let out, below):** ____\n- **Transfers outside the country, and their safeguards:** ____\n- **Organisational measures (who has admin keys, training, breach procedure):** ____\n\n## Personal data held, and why\n\nEach object below belongs to one person, the one whose id is the object's id, except lists of several people's entries, where each entry belongs to the person it names.\n\n| Object | Field | Category | Purposes |\n|---|---|---|---|\n");
    for o in program.objects.iter().filter(|o| !o.pii.is_empty()) {
        for p in &o.pii {
            let special = if SPECIAL_CATEGORIES.contains(&&*p.category) { " (special category)" } else { "" };
            out.push_str(&format!("| {} | {} | {}{special} | {} |\n", o.name, p.field, p.category, p.purposes.join(", ")));
        }
    }
    out.push_str("\n## Where it is let out\n\nPersonal data cannot leave its owner (network, plugins and AI models, events, errors, logs, other callers) except here, each with a stated purpose:\n\n");
    let facts = tj_core::facts(src);
    if facts.reveals.is_empty() {
        out.push_str("- Nowhere.\n");
    }
    for r in &facts.reveals {
        out.push_str(&format!("- `{}`: {}, for {}\n", place(src, r.at), r.fields.join(", "), r.purpose));
    }
    out.push_str("\n## Where it is sent (recipients)\n\n");
    if facts.transfers.is_empty() {
        out.push_str("- Nowhere outside the server.\n");
    }
    for t in &facts.transfers {
        out.push_str(&format!("- `{}`: {} to {}\n", place(src, t.at), t.fields.join(", "), destination(&t.to)));
    }
    out.push_str("\n## How long it is kept\n\n");
    for o in program.objects.iter().filter(|o| o.belongs_to_a_person() || !o.pii.is_empty()) {
        out.push_str(&format!("- **{}**: {}\n", o.name, kept(o)));
    }
    out.push_str("\n## Security measures the runtime provides\n\n- Access rules on every object and method (`tj check --access`), refusals audited.\n- Personal fields shown only to the readers each field names (by default its owner), and masked for everyone else and for every tool.\n- A tamper-evident audit log of calls, reads of personal data, refusals and admin requests, with people as pseudonyms.\n- With `TJ_KEY_FILE`: encryption at rest, and a key per person-owned object, destroyed on erasure so backups cannot be read. Lists of several people's entries are sealed under the store's key: erasure removes the entries from the live data, and backups keep them until they expire.\n- Exports and erasures on request (`tj privacy`, `tj:privacy`), audited.\n- Whether encryption is on for a given server is in its startup line: ____\n");
    out
}

/// `file:line` of a byte offset into `src` with its built-in modules added (as the checks
/// report offsets).
pub fn place(src: &str, at: u32) -> String {
    let full = modules::with_built_ins(src);
    let at = at as usize;
    modules::files(&full).iter().rfind(|f| f.start <= at && at < f.end).map_or_else(String::new, |f| format!("{}:{}", f.name, full[f.start..at].matches('\n').count() + 1))
}

/// Where personal data goes, in words.
pub fn destination(to: &tj_core::Destination) -> String {
    match to {
        tj_core::Destination::Host(h) => h.clone(),
        tj_core::Destination::Cleartext(h) => format!("{h} over plain HTTP"),
        tj_core::Destination::Plugin(m) => format!("the plugin {m}"),
        tj_core::Destination::Unknown => "a URL whose host the code does not fix".into(),
    }
}

/// `tj privacy export|erase <person> [--target <url>]`.
pub fn run(args: &[String]) -> Result<(), String> {
    let usage = "usage: tj privacy export|erase <person id> [--target <url>]";
    let (action, subject) = match args {
        [a, s, ..] if (a == "export" || a == "erase") && !s.starts_with("--") => (a.as_str(), s.as_str()),
        _ => return Err(usage.into()),
    };
    let target = match &args[2..] {
        [] => "http://127.0.0.1:4700",
        [flag, url] if flag == "--target" => url.as_str(),
        _ => return Err(usage.into()),
    };
    let url = format!("{}/_tj/privacy", target.trim_end_matches('/'));
    let mut req = ureq::post(&url).set("Content-Type", "application/json");
    if let Some(h) = crate::auth::client_header() {
        req = req.set("Authorization", &h);
    }
    let body = match req.send_string(&serde_json::json!({ "action": action, "subject": subject }).to_string()) {
        Ok(r) | Err(ureq::Error::Status(_, r)) => r.into_string().map_err(|e| e.to_string())?,
        Err(e) => return Err(format!("cannot reach {url}: {e}")),
    };
    let reply: serde_json::Value = serde_json::from_str(&body).map_err(|e| format!("bad reply from {url}: {e}"))?;
    if let Some(e) = reply["error"].as_str() {
        return Err(e.to_string());
    }
    println!("{}", serde_json::to_string_pretty(&reply["ok"]).expect("JSON serializes"));
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_data_map_lists_every_personal_field() {
        let src = "@server @read(\"owner\", \"support\") object Account {\n  @pii(\"contact\", \"account\", \"billing\") email: string = \"\"\n  @pii(\"health\", \"care\") notes: string = \"\"\n  plan: string = \"free\"\n}\n";
        let r = report(&tj_core::compile(src).unwrap());
        assert!(r.contains("Account  (id: the person's id; read: owner, support)"), "{r}");
        assert!(r.contains("  email  contact  for account, billing  seen by: owner\n") && r.contains("  notes  health  special category  for care  seen by: owner\n") && !r.contains("plan"), "{r}");
        assert!(report(&tj_core::compile("object A { n: number = 0 }").unwrap()).starts_with("no personal data"));
    }

    #[test]
    fn the_record_of_processing_lists_data_reveals_and_how_long_it_is_kept() {
        let src = "@server @read(\"owner\") @retain(\"30d\") @legalHold(\"365d\") object Account {
  @pii(\"contact\", \"account\", \"billing\") email: string = \"\"
  @allow(\"support\") async mail(): string {
    return reveal(this.email, \"billing\")
  }
}
";
        let r = record(src, &tj_core::compile(src).unwrap());
        assert!(r.contains("| Account | email | contact | account, billing |"), "{r}");
        assert!(r.contains("- `app.tj:4`: Account.email, for billing"), "{r}");
        assert!(r.contains("**Account**: erased 30 days after it was last changed; at least 365 days after the last change, even when erased (legal hold)"), "{r}");
        assert!(r.contains("**Lawful basis for each purpose:** ____"), "{r}");
        assert_eq!((span(6.0 * 3_600_000.0), span(86_400_000.0), span(90_000.0)), ("6 hours".to_string(), "1 day".to_string(), "1.5 minutes".to_string()));
        assert!(r.contains("**Controller, contact and data protection officer:** ____"), "{r}");
    }
}
